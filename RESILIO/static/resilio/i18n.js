let interfaceLanguage = "en";
try {
  interfaceLanguage =
    localStorage.getItem("resilio-language") === "bn" ? "bn" : "en";
} catch (e) {}
function tr(text) {
  if (interfaceLanguage !== "bn") return text;
  if (BN[text]) return BN[text];
  if (typeof LOCAL_AREAS !== "undefined") {
    if (LOCAL_AREAS.district_bn[text.toLowerCase()])
      return LOCAL_AREAS.district_bn[text.toLowerCase()];
    const u = LOCAL_AREAS.upazilas.find((x) => x.name === text);
    if (u) return u.bn_name;
  }
  return text
    .replace(/^Notifications \((\d+)\)$/, "বিজ্ঞপ্তি ($1)")
    .replace(
      /^#(\d+) · (medical|trapped|evacuation|flood|other)$/,
      (_, id, kind) => "#" + id + " · " + BN[kind],
    )
    .replace(/^(\d+) people · /, "$1 জন · ")
    .replace(/^Last confirmed: /, "সর্বশেষ নিশ্চিত: ")
    .replace(/^Pending requests: /, "সিঙ্ক বাকি অনুরোধ: ")
    .replace(/^Last public update: /, "সর্বশেষ প্রকাশ্য তথ্য: ")
    .replace(/^View resources in /, "এই জেলার সহায়তা দেখুন: ")
    .replace(/^Your detected district: /, "আপনার শনাক্ত জেলা: ")
    .replace(/^Updated /, "হালনাগাদ ")
    .replace(/^Assigned volunteer: /, "দায়িত্বপ্রাপ্ত স্বেচ্ছাসেবক: ")
    .replace(/ spaces available$/, "টি স্থান খালি")
    .replace(/ km straight-line distance$/, " কিমি সরলরেখার দূরত্ব");
}
const languageSources = new WeakMap();
let languageBusy = false;
function translateInterface() {
  if (languageBusy) return;
  languageBusy = true;
  document.documentElement.lang = interfaceLanguage;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) {
    if (
      n.parentElement?.closest(
        "script,style,textarea,[data-user-content],.leaflet-control-attribution",
      )
    )
      continue;
    let saved = languageSources.get(n);
    if (!saved || n.data !== saved.output) saved = { source: n.data };
    const trimmed = saved.source.trim();
    const out =
      interfaceLanguage === "bn"
        ? saved.source.replace(trimmed, tr(trimmed))
        : saved.source;
    if (n.data !== out) n.data = out;
    saved.output = out;
    languageSources.set(n, saved);
  }
  for (const b of document.querySelectorAll("[data-language-toggle]")) {
    const label = interfaceLanguage === "bn" ? "English" : "বাংলা";
    if (b.textContent !== label) b.textContent = label;
    b.setAttribute(
      "aria-label",
      interfaceLanguage === "bn" ? "Switch to English" : "বাংলায় দেখুন",
    );
  }
  languageBusy = false;
}
function initLanguage() {
  document.querySelectorAll("[data-language-toggle]").forEach((b) =>
    b.addEventListener("click", () => {
      interfaceLanguage = interfaceLanguage === "en" ? "bn" : "en";
      try {
        localStorage.setItem("resilio-language", interfaceLanguage);
      } catch (e) {}
      translateInterface();
    }),
  );
  translateInterface();
  let pending = false;
  new MutationObserver(() => {
    if (pending) return;
    pending = true;
    queueMicrotask(() => {
      pending = false;
      translateInterface();
    });
  }).observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
}
if (document.readyState === "loading")
  document.addEventListener("DOMContentLoaded", initLanguage);
else initLanguage();
