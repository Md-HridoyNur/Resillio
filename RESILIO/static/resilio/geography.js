function geoCatalog() {
  return state.public?.geography || BD_CATALOG;
}
function districtDivision(d) {
  return d.division_id || d.division;
}
function districtInfo(code) {
  return geoCatalog().districts.find((d) => d.code === code);
}
function geoFields(parent, values = {}, required = false, onChange = null) {
  parent.replaceChildren();
  const catalog = geoCatalog();
  const division = el("select"),
    district = el("select"),
    upazila = el("select");
  division.name = "division";
  district.name = "district";
  upazila.name = "upazila";
  division.required = district.required = required;
  function fill(select, rows, label) {
    select.replaceChildren();
    const o = el("option", label);
    o.value = "";
    select.append(o);
    rows.forEach((row) => {
      const n = el("option", row.name);
      n.value = row.code;
      select.append(n);
    });
  }
  fill(
    division,
    catalog.divisions,
    required ? "Select division" : "All / not selected",
  );
  const selected = districtInfo(values.district);
  division.value = selected
    ? districtDivision(selected)
    : values.division || "";
  const fillDistrict = () =>
    fill(
      district,
      catalog.districts.filter(
        (d) => !division.value || districtDivision(d) === division.value,
      ),
      required ? "Select district" : "All / not selected",
    );
  const refreshLocality = () => {
    fill(
      upazila,
      (
        catalog.upazilas ||
        (typeof LOCAL_AREAS !== "undefined" ? LOCAL_AREAS.upazilas : [])
      ).filter((u) => u.district === district.value),
      "All / not listed",
    );
    upazila.disabled = !district.value;
  };
  fillDistrict();
  district.value = values.district || "";
  refreshLocality();
  upazila.value = values.upazila || "";
  const change = () => {
    if (onChange) onChange(division.value, district.value, upazila.value);
  };
  division.addEventListener("change", () => {
    fillDistrict();
    refreshLocality();
    change();
  });
  district.addEventListener("change", () => {
    if (district.value)
      division.value = districtDivision(districtInfo(district.value));
    refreshLocality();
    change();
  });
  upazila.addEventListener("change", change);
  for (const [label, input] of [
    ["Division", division],
    ["District", district],
    ["Upazila", upazila],
  ]) {
    const l = el("label", label);
    l.append(input);
    parent.append(l);
  }
  return { division, district, upazila, refreshLocality };
}
